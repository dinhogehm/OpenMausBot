import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { buildProofCommand } from "../src/linux-proof.ts";

// Opt-in local acceptance fixture. It creates only disposable, network-disabled
// containers and never mounts a host directory or passes any host credentials.
test("the fixed proof program creates and reads its artifact inside real Linux", { timeout: 60_000 }, () => {
  const name = `veltram-proof-fixture-${randomUUID()}`;
  const input = {
    runId: "fixture", organizationId: "fixture_org", workspaceId: "fixture_workspace", generation: 1,
    message: "Prova real: 🚀\n$(touch /workspace/injected); `id` ' \" \\ \u0000\n", delayMs: 30, deadlineAt: Date.now() + 60_000,
  };
  const command = buildProofCommand(input);
  try {
    const result = execFileSync("docker", [
      "run", "--name", name, "--rm", "-i", "--platform", "linux/amd64", "--network", "none",
      "--read-only", "--tmpfs", "/workspace:rw,noexec,nosuid,size=1m", "--pids-limit", "32", "--memory", "256m", "--cpus", "0.5",
      "node:24.20.0-trixie-slim", ...command.argv,
    ], { input: command.stdin, timeout: 45_000, maxBuffer: 64 * 1024 });
    assert.equal(result.toString("utf8"), input.message);
  } finally {
    // The name was generated by this fixture; never target other containers.
    try { execFileSync("docker", ["rm", "-f", name], { stdio: "ignore", timeout: 10_000 }); } catch { /* --rm already removed it */ }
  }
});
